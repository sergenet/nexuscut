const { withAppBuildGradle } = require('expo/config-plugins');

/**
 * Injects NexusCut's release signing config into android/app/build.gradle on every
 * `expo prebuild`, so the upload keystore survives native project regeneration.
 *
 * Why this exists: mobile/.gitignore ignores the whole /android directory, so a
 * hand-edited build.gradle is untracked. Without this mod, one `npx expo prebuild`
 * would silently restore the stock `signingConfig signingConfigs.debug` line and every
 * later release build would be debug-signed — which Play rejects, and which would
 * permanently split the app's signing identity if it ever reached users.
 *
 * Credentials stay out of git: this only reads them at build time from
 * mobile/keystore.properties, which is ignored together with the .jks it points at.
 */

// Seeded by the loader block below. Its presence means the mod already ran, so
// prebuild re-runs (and this plugin being applied twice) are no-ops.
const ALREADY_APPLIED = 'def hasUploadKey = false';

const LOADER = `// @generated by plugins/withAndroidReleaseSigning.js - re-applied on every expo prebuild.
// Reads the upload key from <mobile>/keystore.properties (git-ignored, as is the .jks).
// Without it, release builds fall back to the debug key and warn loudly: Play rejects
// debug-signed artifacts.
def keystorePropertiesFile = rootProject.file('../keystore.properties')
def keystoreProperties = new Properties()
def hasUploadKey = false
if (keystorePropertiesFile.exists()) {
    keystorePropertiesFile.withInputStream { keystoreProperties.load(it) }
    def configuredStore = keystoreProperties['storeFile']
    if (configuredStore) {
        def resolvedStore = new File(keystorePropertiesFile.parentFile, configuredStore)
        keystoreProperties['storeFile'] = resolvedStore.absolutePath
        boolean complete = [
            keystoreProperties['storePassword'],
            keystoreProperties['keyAlias'],
            keystoreProperties['keyPassword'],
        ].every { it }
        if (resolvedStore.exists() && complete) {
            hasUploadKey = true
        } else {
            logger.warn('WARNING: keystore.properties found but unusable - store file exists: ' +
                resolvedStore.exists() + ', credentials complete: ' + complete)
        }
    }
}
if (!hasUploadKey) {
    logger.warn('WARNING: no upload key configured; release builds are signed with the DEBUG key ' +
        'and Play will reject them. Expected ../keystore.properties pointing at the upload .jks.')
}
`;

/** Index of the brace matching the one at `openIndex`. */
function matchingBrace(contents, openIndex) {
  let depth = 0;
  for (let i = openIndex; i < contents.length; i++) {
    if (contents[i] === '{') depth++;
    else if (contents[i] === '}') {
      depth--;
      if (depth === 0) return i;
    }
  }
  throw new Error('withAndroidReleaseSigning: unbalanced braces in android/app/build.gradle');
}

/** Index of the opening brace of the `name {` block, or -1 when absent. */
function blockOpen(contents, name, fromIndex = 0) {
  const start = contents.indexOf(`${name} {`, fromIndex);
  if (start === -1) return -1;
  return contents.indexOf('{', start);
}

function indentOf(contents, index) {
  const lineStart = contents.lastIndexOf('\n', index) + 1;
  return contents.slice(lineStart, index);
}

function releaseSigningConfig(indent) {
  const inner = `${indent}    `;
  const body = `${inner}    `;
  return (
    `${indent}if (hasUploadKey) {\n` +
    `${inner}release {\n` +
    `${body}storeFile new File(keystoreProperties['storeFile'])\n` +
    `${body}storePassword keystoreProperties['storePassword']\n` +
    `${body}keyAlias keystoreProperties['keyAlias']\n` +
    `${body}keyPassword keystoreProperties['keyPassword']\n` +
    `${inner}}\n` +
    `${indent}}\n`
  );
}

function transformAppBuildGradle(contents) {
  if (contents.includes(ALREADY_APPLIED)) {
    return contents;
  }

  let next = contents;

  // 1. Loader: keystore.properties -> hasUploadKey, above the android { } block.
  const androidOpen = blockOpen(next, 'android');
  if (androidOpen === -1) {
    throw new Error('withAndroidReleaseSigning: could not find `android {` in build.gradle');
  }
  const androidLineStart = next.lastIndexOf('\n', androidOpen) + 1;
  next = `${next.slice(0, androidLineStart)}${LOADER}${next.slice(androidLineStart)}`;

  // 2. signingConfigs: register the release config that the loader enabled.
  const scOpen = blockOpen(next, 'signingConfigs');
  if (scOpen === -1) {
    throw new Error('withAndroidReleaseSigning: could not find `signingConfigs {` in build.gradle');
  }
  const scClose = matchingBrace(next, scOpen);
  // Align with the existing `debug {` child so the block reads as a sibling of it.
  const debugLine = next.indexOf('debug', scOpen);
  const childIndent = debugLine === -1 ? `${indentOf(next, scClose)}    ` : indentOf(next, debugLine);
  const insertAt = next.lastIndexOf('\n', scClose) + 1;
  next = `${next.slice(0, insertAt)}${releaseSigningConfig(childIndent)}${next.slice(insertAt)}`;

  // 3. buildTypes.release: point it at the upload key, leaving buildTypes.debug alone.
  const btOpen = blockOpen(next, 'buildTypes');
  if (btOpen === -1) {
    throw new Error('withAndroidReleaseSigning: could not find `buildTypes {` in build.gradle');
  }
  const btClose = matchingBrace(next, btOpen);
  const releaseOpen = blockOpen(next, 'release', btOpen);
  if (releaseOpen === -1 || releaseOpen > btClose) {
    throw new Error('withAndroidReleaseSigning: could not find `release {` inside buildTypes');
  }
  const debugSigning = 'signingConfig signingConfigs.debug';
  const debugSigningAt = next.indexOf(debugSigning, releaseOpen);
  if (debugSigningAt === -1 || debugSigningAt > matchingBrace(next, releaseOpen)) {
    throw new Error(
      'withAndroidReleaseSigning: release buildType has no `signingConfig signingConfigs.debug` line to replace'
    );
  }
  next =
    next.slice(0, debugSigningAt) +
    'signingConfig hasUploadKey ? signingConfigs.release : signingConfigs.debug' +
    next.slice(debugSigningAt + debugSigning.length);

  // 4. Drop the stock "generate your own keystore" caution, which this now does.
  next = next.replace(
    /[ \t]*\/\/ Caution! In production, you need to generate your own keystore file\.\n[ \t]*\/\/ see https:\/\/reactnative\.dev\/docs\/signed-apk-android\.\n/,
    ''
  );

  return next;
}

module.exports = function withAndroidReleaseSigning(config) {
  return withAppBuildGradle(config, (configWithMod) => {
    configWithMod.modResults.contents = transformAppBuildGradle(configWithMod.modResults.contents);
    return configWithMod;
  });
};

// Exposed for tests; Expo only uses the default callable export.
module.exports.transformAppBuildGradle = transformAppBuildGradle;
